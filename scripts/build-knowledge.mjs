// Builds the chatbot's knowledge base (api/_knowledge.js) from the site copy in src/data.
// Run automatically before `npm run build`; run `node scripts/build-knowledge.mjs` after editing site copy.
// Uses Node's built-in TypeScript type stripping (Node 22.18+ / 23.6+).
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

// The data files import each other without the ".ts" extension (Vite style); add it for Node.
register('data:text/javascript,' + encodeURIComponent(`
export async function resolve(specifier, context, next) {
  if (specifier.startsWith('.') && !/\\.[a-z]+$/i.test(specifier)) {
    try { return await next(specifier + '.ts', context); } catch {}
  }
  return next(specifier, context);
}`), pathToFileURL('./'));

const load = name => import(new URL(`../src/data/${name}.ts`, import.meta.url));
const content = await load('content');
const solutions = await load('solutions');
const platform = await load('platform');
const extras = (await load('details-extra')).DETAIL_EXTRAS;

// Drop presentation-only fields so the model sees just the facts.
const SKIP = new Set(['icon', 'image', 'imageAlt', 'flag', 'phoneHref', 'highlight', 'key']);
const clean = value => {
  if (Array.isArray(value)) return value.map(clean);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).filter(([k]) => !SKIP.has(k)).map(([k, v]) => [k, clean(v)]));
  }
  return value;
};

const pagePath = (kind, slug) => ({ industry: `/industries/${slug}`, initiative: `/solutions/${slug}`, platform: `/platform/${slug}` }[kind] ?? `/${slug}`);
const details = [...solutions.INDUSTRY_DETAILS, ...solutions.INITIATIVE_DETAILS, ...platform.PLATFORM_DETAILS].map(d => ({
  page: pagePath(d.kind, d.slug),
  ...clean(d),
  ...(extras[d.slug] ? { more: clean(extras[d.slug]) } : {}),
}));

const { SITE, OFFICES, JOBS } = content;

const knowledge = {
  company: {
    name: SITE.name,
    summary: 'ALPHAZOX designs, builds and runs AI agents and enterprise applications (web and mobile apps, workflow automation, integrations, legacy modernization), governed, secure and ready to scale. Delivery teams in the USA and India.',
    mission: 'Make enterprise software fast to build and safe to run. Most organizations know where AI and modern apps could help; legacy systems, scarce skills and governance risk slow them down. ALPHAZOX closes that gap. We start small with one valuable process, prove results in weeks, then scale what works, reusing components, integrations and guardrails.',
    contact: {
      email: SITE.email,
      phoneIndia: SITE.phoneIndia,
      phoneUSA: SITE.phoneUS,
      linkedin: SITE.linkedin,
      x: SITE.x,
      instagram: SITE.instagram,
      offices: clean(OFFICES),
      contactPage: '/contact',
      bookDemo: 'The "Book a demo" button at the top of every page opens a short form for a free 30-minute discovery call.',
    },
    pages: content.NAV,
  },
  careers: {
    page: '/careers',
    howToApply: 'Apply on the Careers page with the application form (resume as PDF/DOC up to 10 MB, cover letter required).',
    openRoleCount: JOBS.length,
    openRoles: JOBS,
    perks: ['Real AI work in production', 'Certifications, mentoring and time to learn', 'Global teams across the USA and India', 'Performance-driven culture with equal growth opportunities'],
  },
  pillars: clean(content.PILLARS),
  agenticAI: {
    page: '/agentic-ai',
    loop: clean(content.AGENT_LOOP),
    compare: content.AGENT_COMPARE,
    lifecycle: clean(content.AGENT_LIFECYCLE),
    capabilities: clean(content.AGENT_CAPABILITIES),
    examples: clean(content.AGENT_EXAMPLES),
    faq: content.AGENT_FAQ,
  },
  useCases: clean(content.USE_CASES),
  initiatives: clean(content.INITIATIVES),
  industries: clean(content.INDUSTRIES),
  governance: clean(content.GOVERNANCE),
  deliveryApproach: clean(content.DELIVERY),
  capabilities: clean(content.CAPABILITIES),
  techStack: clean(content.TECH_STACK),
  values: clean(content.VALUES),
  whyUs: clean(solutions.WHY_US),
  faq: content.FAQ,
  detailPages: details,
};

const out = fileURLToPath(new URL('../api/_knowledge.js', import.meta.url));
const json = JSON.stringify(knowledge);
writeFileSync(out, `// Generated by scripts/build-knowledge.mjs from src/data. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(json)};\n`);
console.log(`[knowledge] wrote ${out} (${(json.length / 1024).toFixed(1)} KB)`);
